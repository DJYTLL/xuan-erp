-- V1 initialization data
-- These rows are idempotent and only provide default dictionaries/configuration.

-- warehouse: 默认仓库。
INSERT INTO warehouse (tenant_id, code, name, address, manager, phone, is_enabled, is_default, remark, created_by, updated_by)
SELECT 1, 'DEFAULT', '默认仓库', NULL, NULL, NULL, true, true, 'V1 默认仓库。', 'system', 'system'
WHERE NOT EXISTS (
    SELECT 1
    FROM warehouse existing
    WHERE existing.tenant_id = 1
      AND existing.code = 'DEFAULT'
      AND existing.deleted_at IS NULL
);

-- warehouse_location: 默认仓库下的默认库位。
INSERT INTO warehouse_location (tenant_id, warehouse_id, code, name, aisle, rack, bin, is_enabled, is_default, remark, created_by, updated_by)
SELECT 1, warehouse.id, 'DEFAULT_BIN', '默认库位', NULL, NULL, NULL, true, true, 'V1 默认库位。', 'system', 'system'
FROM warehouse
WHERE warehouse.tenant_id = 1
  AND warehouse.code = 'DEFAULT'
  AND warehouse.deleted_at IS NULL
  AND NOT EXISTS (
      SELECT 1
      FROM warehouse_location existing
      WHERE existing.tenant_id = 1
        AND existing.warehouse_id = warehouse.id
        AND existing.code = 'DEFAULT_BIN'
        AND existing.deleted_at IS NULL
  );
