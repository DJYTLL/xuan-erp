-- xuan-warehouse initial database objects
-- Generated from the legacy wms_backend structure and current Xuan ERP service boundaries.
-- Run this migration after connecting Flyway to this service's own database.

CREATE TABLE IF NOT EXISTS warehouse (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    tenant_id bigint NOT NULL,
    code varchar(100) NOT NULL,
    name varchar(200) NOT NULL,
    address varchar(500),
    manager varchar(100),
    phone varchar(50),
    is_enabled boolean DEFAULT true NOT NULL,
    is_default boolean DEFAULT false NOT NULL,
    remark varchar(500),
    created_by varchar(100),
    created_at timestamptz DEFAULT now() NOT NULL,
    updated_by varchar(100),
    updated_at timestamptz DEFAULT now() NOT NULL,
    deleted_by varchar(100),
    delete_reason varchar(500),
    deleted_at timestamptz,
    CONSTRAINT pk_warehouse PRIMARY KEY (id)
);
COMMENT ON TABLE warehouse IS '仓库表。';
COMMENT ON COLUMN warehouse.id IS '主键';
COMMENT ON COLUMN warehouse.tenant_id IS '租户 ID，来源于 xuan-tenant';
COMMENT ON COLUMN warehouse.code IS '仓库编码';
COMMENT ON COLUMN warehouse.name IS '仓库名称';
COMMENT ON COLUMN warehouse.address IS '地址';
COMMENT ON COLUMN warehouse.manager IS '负责人';
COMMENT ON COLUMN warehouse.phone IS '联系电话';
COMMENT ON COLUMN warehouse.is_enabled IS '是否启用';
COMMENT ON COLUMN warehouse.is_default IS '是否默认仓库';
COMMENT ON COLUMN warehouse.remark IS '备注';
COMMENT ON COLUMN warehouse.created_by IS '创建人';
COMMENT ON COLUMN warehouse.created_at IS '创建时间';
COMMENT ON COLUMN warehouse.updated_by IS '更新人';
COMMENT ON COLUMN warehouse.updated_at IS '更新时间';
COMMENT ON COLUMN warehouse.deleted_by IS '删除人';
COMMENT ON COLUMN warehouse.delete_reason IS '删除原因';
COMMENT ON COLUMN warehouse.deleted_at IS '逻辑删除时间';
CREATE INDEX IF NOT EXISTS idx_warehouse_warehouse_code_active
    ON warehouse (tenant_id, code)
    WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_warehouse_default
    ON warehouse (tenant_id)
    WHERE is_default = true AND deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_warehouse_name
    ON warehouse (tenant_id, name);
CREATE INDEX IF NOT EXISTS idx_warehouse_warehouse_tenant_deleted
    ON warehouse (tenant_id, deleted_at);

