INSERT INTO iam_resource_column (
    resource_key, column_key, column_name, data_type, mask_type, is_enabled, sort_no, created_by, updated_by
)
SELECT seed.resource_key, seed.column_key, seed.column_name, seed.data_type, seed.mask_type, true, seed.sort_no, 'system', 'system'
FROM (
    VALUES
    ('tenant', 'code', '租户编码', 'STRING', NULL, 10),
    ('tenant', 'name', '租户名称', 'STRING', NULL, 20),
    ('tenant', 'status', '租户状态', 'ENUM', NULL, 30),
    ('tenant', 'contactName', '联系人', 'STRING', NULL, 40),
    ('tenant', 'contactPhone', '联系电话', 'STRING', 'PHONE', 50),
    ('tenant', 'remark', '备注', 'STRING', NULL, 60),
    ('tenant', 'currentPlanName', '当前套餐名称', 'STRING', NULL, 70),
    ('tenant', 'primaryDomain', '主域名', 'STRING', NULL, 80)
) AS seed(resource_key, column_key, column_name, data_type, mask_type, sort_no)
WHERE NOT EXISTS (
    SELECT 1
    FROM iam_resource_column existing
    WHERE existing.resource_key = seed.resource_key
      AND existing.column_key = seed.column_key
      AND existing.deleted_at IS NULL
);

INSERT INTO iam_column_permission_template (
    tenant_id, code, name, description, is_enabled, created_by, updated_by
)
SELECT seed.tenant_id, seed.code, seed.name, seed.description, true, 'system', 'system'
FROM (
    VALUES
    (0::bigint, 'tenant_admin_default', '租户管理列权限模板', '租户管理页面默认明文模板'),
    (0::bigint, 'tenant_readonly_masked', '租户只读列权限模板', '租户只读页面隐藏备注并脱敏联系电话')
) AS seed(tenant_id, code, name, description)
WHERE NOT EXISTS (
    SELECT 1
    FROM iam_column_permission_template existing
    WHERE existing.tenant_id = seed.tenant_id
      AND existing.code = seed.code
      AND existing.deleted_at IS NULL
);

WITH template_items(template_code, column_key, access_mode) AS (
    VALUES
    ('tenant_admin_default', 'code', 'VISIBLE'),
    ('tenant_admin_default', 'name', 'VISIBLE'),
    ('tenant_admin_default', 'status', 'VISIBLE'),
    ('tenant_admin_default', 'contactName', 'VISIBLE'),
    ('tenant_admin_default', 'contactPhone', 'VISIBLE'),
    ('tenant_admin_default', 'remark', 'VISIBLE'),
    ('tenant_admin_default', 'currentPlanName', 'VISIBLE'),
    ('tenant_admin_default', 'primaryDomain', 'VISIBLE'),
    ('tenant_readonly_masked', 'code', 'VISIBLE'),
    ('tenant_readonly_masked', 'name', 'VISIBLE'),
    ('tenant_readonly_masked', 'status', 'VISIBLE'),
    ('tenant_readonly_masked', 'contactName', 'HIDDEN'),
    ('tenant_readonly_masked', 'contactPhone', 'MASKED'),
    ('tenant_readonly_masked', 'remark', 'HIDDEN'),
    ('tenant_readonly_masked', 'currentPlanName', 'VISIBLE'),
    ('tenant_readonly_masked', 'primaryDomain', 'VISIBLE')
)
INSERT INTO iam_column_permission_template_item (
    template_id, resource_column_id, access_mode, created_by, updated_by
)
SELECT template.id, resource_column.id, template_items.access_mode, 'system', 'system'
FROM template_items
JOIN iam_column_permission_template template
  ON template.tenant_id = 0
 AND template.code = template_items.template_code
 AND template.deleted_at IS NULL
JOIN iam_resource_column resource_column
  ON resource_column.resource_key = 'tenant'
 AND resource_column.column_key = template_items.column_key
 AND resource_column.deleted_at IS NULL
WHERE NOT EXISTS (
    SELECT 1
    FROM iam_column_permission_template_item existing
    WHERE existing.template_id = template.id
      AND existing.resource_column_id = resource_column.id
      AND existing.deleted_at IS NULL
);
