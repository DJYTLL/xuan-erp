COMMENT ON COLUMN iam_column_permission_template.name IS '模板名称';
COMMENT ON COLUMN iam_column_permission_template.description IS '模板描述';
COMMENT ON COLUMN iam_column_permission_template.is_enabled IS '是否启用';
COMMENT ON COLUMN iam_column_permission_template.created_by IS '创建人';
COMMENT ON COLUMN iam_column_permission_template.created_at IS '创建时间';
COMMENT ON COLUMN iam_column_permission_template.updated_by IS '更新人';
COMMENT ON COLUMN iam_column_permission_template.updated_at IS '更新时间';
COMMENT ON COLUMN iam_column_permission_template.deleted_by IS '删除人';
COMMENT ON COLUMN iam_column_permission_template.delete_reason IS '删除原因';
