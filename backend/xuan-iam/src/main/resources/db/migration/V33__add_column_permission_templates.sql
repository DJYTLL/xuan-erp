CREATE TABLE IF NOT EXISTS iam_resource_column (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    resource_key varchar(120) NOT NULL,
    column_key varchar(120) NOT NULL,
    column_name varchar(200) NOT NULL,
    data_type varchar(60),
    mask_type varchar(60),
    is_enabled boolean DEFAULT true NOT NULL,
    sort_no integer DEFAULT 0 NOT NULL,
    created_by varchar(100),
    created_at timestamptz DEFAULT now() NOT NULL,
    updated_by varchar(100),
    updated_at timestamptz DEFAULT now() NOT NULL,
    deleted_by varchar(100),
    delete_reason varchar(500),
    deleted_at timestamptz,
    CONSTRAINT pk_iam_resource_column PRIMARY KEY (id)
);
COMMENT ON TABLE iam_resource_column IS 'IAM 资源字段清单，定义业务资源可参与列权限控制的字段。';
COMMENT ON COLUMN iam_resource_column.id IS '主键';
COMMENT ON COLUMN iam_resource_column.resource_key IS '资源标识，例如 tenant 表示租户列表资源';
COMMENT ON COLUMN iam_resource_column.column_key IS '字段标识，对应业务接口 DTO 字段名';
COMMENT ON COLUMN iam_resource_column.column_name IS '字段中文名称';
COMMENT ON COLUMN iam_resource_column.data_type IS '字段数据类型，用于前端展示和后续规则扩展';
COMMENT ON COLUMN iam_resource_column.mask_type IS '脱敏类型，例如 PHONE 表示手机号脱敏';
COMMENT ON COLUMN iam_resource_column.is_enabled IS '是否启用';
COMMENT ON COLUMN iam_resource_column.sort_no IS '排序';
COMMENT ON COLUMN iam_resource_column.created_by IS '创建人';
COMMENT ON COLUMN iam_resource_column.created_at IS '创建时间';
COMMENT ON COLUMN iam_resource_column.updated_by IS '更新人';
COMMENT ON COLUMN iam_resource_column.updated_at IS '更新时间';
COMMENT ON COLUMN iam_resource_column.deleted_by IS '删除人';
COMMENT ON COLUMN iam_resource_column.delete_reason IS '删除原因';
COMMENT ON COLUMN iam_resource_column.deleted_at IS '逻辑删除时间';
CREATE UNIQUE INDEX IF NOT EXISTS idx_iam_resource_column_key_active
    ON iam_resource_column (resource_key, column_key)
    WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_iam_resource_column_resource
    ON iam_resource_column (resource_key, is_enabled, sort_no)
    WHERE deleted_at IS NULL;

