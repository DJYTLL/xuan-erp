    WHERE deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS iam_column_permission_template_item (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    template_id bigint NOT NULL,
    resource_column_id bigint NOT NULL,
    access_mode varchar(30) NOT NULL,
    created_by varchar(100),
    created_at timestamptz DEFAULT now() NOT NULL,
    updated_by varchar(100),
    updated_at timestamptz DEFAULT now() NOT NULL,
    deleted_by varchar(100),
    delete_reason varchar(500),
    deleted_at timestamptz,
    CONSTRAINT pk_iam_column_permission_template_item PRIMARY KEY (id),
    CONSTRAINT ck_iam_column_permission_template_item_access
        CHECK (access_mode IN ('VISIBLE', 'MASKED', 'HIDDEN'))
);
COMMENT ON TABLE iam_column_permission_template_item IS 'IAM 列权限模板明细，定义模板中每个字段的访问级别。';
COMMENT ON COLUMN iam_column_permission_template_item.id IS '主键';
COMMENT ON COLUMN iam_column_permission_template_item.template_id IS '列权限模板 ID';
COMMENT ON COLUMN iam_column_permission_template_item.resource_column_id IS '资源字段 ID';
COMMENT ON COLUMN iam_column_permission_template_item.access_mode IS '访问级别：VISIBLE 明文可见，MASKED 脱敏可见，HIDDEN 隐藏不可见';
COMMENT ON COLUMN iam_column_permission_template_item.created_by IS '创建人';
COMMENT ON COLUMN iam_column_permission_template_item.created_at IS '创建时间';
COMMENT ON COLUMN iam_column_permission_template_item.updated_by IS '更新人';
COMMENT ON COLUMN iam_column_permission_template_item.updated_at IS '更新时间';
COMMENT ON COLUMN iam_column_permission_template_item.deleted_by IS '删除人';
COMMENT ON COLUMN iam_column_permission_template_item.delete_reason IS '删除原因';
COMMENT ON COLUMN iam_column_permission_template_item.deleted_at IS '逻辑删除时间';
CREATE UNIQUE INDEX IF NOT EXISTS idx_iam_column_permission_template_item_active
    ON iam_column_permission_template_item (template_id, resource_column_id)
    WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_iam_column_permission_template_item_column
    ON iam_column_permission_template_item (resource_column_id)
    WHERE deleted_at IS NULL;

