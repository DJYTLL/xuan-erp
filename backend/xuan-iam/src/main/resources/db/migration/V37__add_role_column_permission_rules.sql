-- 追加角色独立列权限规则和管理页面；租户列权限模板池只作为角色可授权上限。
CREATE TABLE IF NOT EXISTS iam_role_column_permission_rule (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    tenant_id bigint NOT NULL,
    role_id bigint NOT NULL,
    resource_column_id bigint NOT NULL,
    access_mode varchar(30) NOT NULL,
    created_by varchar(100),
    created_at timestamptz DEFAULT now() NOT NULL,
    updated_by varchar(100),
    updated_at timestamptz DEFAULT now() NOT NULL,
    deleted_by varchar(100),
    delete_reason varchar(500),
    deleted_at timestamptz,
    CONSTRAINT pk_iam_role_column_permission_rule PRIMARY KEY (id),
    CONSTRAINT ck_iam_role_column_permission_rule_access
        CHECK (access_mode IN ('VISIBLE', 'MASKED', 'HIDDEN'))
);

COMMENT ON TABLE iam_role_column_permission_rule IS '角色列权限规则表，定义租户内每个角色对资源字段的明文、脱敏或隐藏访问级别。';
COMMENT ON COLUMN iam_role_column_permission_rule.id IS '主键';
COMMENT ON COLUMN iam_role_column_permission_rule.tenant_id IS '租户 ID，必须与角色所属租户一致';
COMMENT ON COLUMN iam_role_column_permission_rule.role_id IS '角色 ID';
COMMENT ON COLUMN iam_role_column_permission_rule.resource_column_id IS '资源字段 ID';
COMMENT ON COLUMN iam_role_column_permission_rule.access_mode IS '访问级别：VISIBLE 明文可见，MASKED 脱敏可见，HIDDEN 隐藏不可见';
COMMENT ON COLUMN iam_role_column_permission_rule.created_by IS '创建人';
COMMENT ON COLUMN iam_role_column_permission_rule.created_at IS '创建时间';
COMMENT ON COLUMN iam_role_column_permission_rule.updated_by IS '更新人';
COMMENT ON COLUMN iam_role_column_permission_rule.updated_at IS '更新时间';
COMMENT ON COLUMN iam_role_column_permission_rule.deleted_by IS '删除人';
COMMENT ON COLUMN iam_role_column_permission_rule.delete_reason IS '删除原因';
COMMENT ON COLUMN iam_role_column_permission_rule.deleted_at IS '逻辑删除时间';

CREATE UNIQUE INDEX IF NOT EXISTS idx_iam_role_column_permission_rule_active
    ON iam_role_column_permission_rule (tenant_id, role_id, resource_column_id)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_iam_role_column_permission_rule_role
    ON iam_role_column_permission_rule (tenant_id, role_id)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_iam_role_column_permission_rule_column
    ON iam_role_column_permission_rule (resource_column_id)
    WHERE deleted_at IS NULL;

INSERT INTO iam_role_column_permission_rule (
    tenant_id, role_id, resource_column_id, access_mode, created_by, updated_by
)
SELECT DISTINCT binding.tenant_id,
       binding.role_id,
       template_item.resource_column_id,
       template_item.access_mode,
       'system-v37',
       'system-v37'
FROM iam_role_column_permission_template_binding binding
JOIN iam_column_permission_template template
  ON template.id = binding.template_id
 AND template.deleted_at IS NULL
 AND template.is_enabled = true
JOIN iam_column_permission_template_item template_item
  ON template_item.template_id = template.id
 AND template_item.deleted_at IS NULL
WHERE binding.deleted_at IS NULL
  AND (
      binding.tenant_id = 0
      OR EXISTS (
          SELECT 1
          FROM iam_tenant_column_permission_template_assignment assignment
          WHERE assignment.tenant_id = binding.tenant_id
            AND assignment.template_id = binding.template_id
            AND assignment.deleted_at IS NULL
      )
  )
  AND NOT EXISTS (
      SELECT 1
      FROM iam_role_column_permission_rule existing
      WHERE existing.tenant_id = binding.tenant_id
        AND existing.role_id = binding.role_id
        AND existing.resource_column_id = template_item.resource_column_id
        AND existing.deleted_at IS NULL
  );

