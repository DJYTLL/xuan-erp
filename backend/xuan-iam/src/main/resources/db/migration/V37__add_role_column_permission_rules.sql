INSERT INTO iam_tenant_menu (tenant_id, menu_id, is_enabled, created_by, updated_by)
SELECT DISTINCT tenant_menu.tenant_id,
       menu.id,
       true,
       'system-v37',
       'system-v37'
FROM iam_tenant_menu tenant_menu
CROSS JOIN iam_menu menu
WHERE tenant_menu.deleted_at IS NULL
  AND menu.code = 'iam-role-column-permission-management'
  AND menu.deleted_at IS NULL
  AND NOT EXISTS (
      SELECT 1
      FROM iam_tenant_menu existing
      WHERE existing.tenant_id = tenant_menu.tenant_id
        AND existing.menu_id = menu.id
        AND existing.deleted_at IS NULL
  );

UPDATE iam_authorization_snapshot snapshot
SET permission_codes = (
        SELECT COALESCE(jsonb_agg(code ORDER BY code), '[]'::jsonb)
        FROM (
            SELECT DISTINCT code
            FROM (
                SELECT jsonb_array_elements_text(COALESCE(snapshot.permission_codes, '[]'::jsonb)) AS code
                UNION ALL
                SELECT source_permission.new_code
                FROM jsonb_array_elements_text(COALESCE(snapshot.permission_codes, '[]'::jsonb)) existing(code)
                JOIN (
                    VALUES
                        ('iam-column-permission:view', 'iam-role-column-permission:view'),
                        ('iam-column-permission:update', 'iam-role-column-permission:update')
                ) AS source_permission(old_code, new_code)
                  ON source_permission.old_code = existing.code
            ) expanded
        ) distinct_code
    ),
    menu_codes = (
        SELECT COALESCE(jsonb_agg(code ORDER BY code), '[]'::jsonb)
        FROM (
            SELECT DISTINCT code
            FROM (
                SELECT jsonb_array_elements_text(COALESCE(snapshot.menu_codes, '[]'::jsonb)) AS code
                UNION ALL
                SELECT 'iam-role-column-permission-management'
                WHERE EXISTS (
                    SELECT 1
                    FROM jsonb_array_elements_text(COALESCE(snapshot.permission_codes, '[]'::jsonb)) existing(code)
                    WHERE existing.code = 'iam-column-permission:view'
                )
            ) expanded
        ) distinct_code
    ),
    column_settings = COALESCE((
        SELECT jsonb_object_agg(resource_key, columns_json)
        FROM (
            SELECT resource_key,
                   jsonb_object_agg(column_key, access_mode ORDER BY column_key) AS columns_json
            FROM (
                SELECT DISTINCT ON (resource_column.resource_key, resource_column.column_key)
                       resource_column.resource_key,
                       resource_column.column_key,
                       rule.access_mode
                FROM jsonb_array_elements_text(COALESCE(snapshot.role_ids, '[]'::jsonb)) role_id_text(role_id)
                JOIN iam_role_column_permission_rule rule
                  ON rule.tenant_id = snapshot.tenant_id
                 AND rule.role_id = role_id_text.role_id::bigint
                 AND rule.deleted_at IS NULL
                JOIN iam_resource_column resource_column
                  ON resource_column.id = rule.resource_column_id
                 AND resource_column.deleted_at IS NULL
                 AND resource_column.is_enabled = true
                ORDER BY resource_column.resource_key,
                         resource_column.column_key,
                         CASE rule.access_mode
                             WHEN 'VISIBLE' THEN 3
                             WHEN 'MASKED' THEN 2
                             ELSE 1
                         END DESC
            ) merged_rule
            GROUP BY resource_key
        ) resource_rule
    ), '{}'::jsonb),
    auth_version = snapshot.auth_version + 1,
    snapshot_hash = 'role-column-permissions-v37:' || snapshot.tenant_id || ':' || snapshot.user_id,
    updated_by = 'system-v37',
    updated_at = now()
WHERE EXISTS (
    SELECT 1
    FROM jsonb_array_elements_text(COALESCE(snapshot.permission_codes, '[]'::jsonb)) existing(code)
    WHERE existing.code IN ('iam-column-permission:view', 'iam-column-permission:update')
)
OR EXISTS (
    SELECT 1
    FROM jsonb_array_elements_text(COALESCE(snapshot.role_ids, '[]'::jsonb)) role_id_text(role_id)
    JOIN iam_role_column_permission_rule rule
      ON rule.tenant_id = snapshot.tenant_id
     AND rule.role_id = role_id_text.role_id::bigint
     AND rule.deleted_at IS NULL
);
