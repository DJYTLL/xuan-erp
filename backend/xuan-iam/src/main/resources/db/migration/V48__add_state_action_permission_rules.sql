-- 追加状态动作权限规则事实源、管理入口和历史授权回填。
-- 状态动作权限只负责“角色在资源状态下可执行哪些动作”，业务状态机仍由各业务服务 DDD 领域模型兜底。

CREATE TABLE IF NOT EXISTS iam_resource_state (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    tenant_id bigint DEFAULT 0 NOT NULL,
    resource_key varchar(120) NOT NULL,
    state_code varchar(120) NOT NULL,
    state_name varchar(120) NOT NULL,
    description varchar(500),
    sort_no integer DEFAULT 0 NOT NULL,
    is_enabled boolean DEFAULT true NOT NULL,
    metadata_json JSONB DEFAULT '{}'::jsonb NOT NULL,
    created_by varchar(100),
    created_at timestamptz DEFAULT now() NOT NULL,
    updated_by varchar(100),
    updated_at timestamptz DEFAULT now() NOT NULL,
    deleted_by varchar(100),
    delete_reason varchar(500),
    deleted_at timestamptz,
    CONSTRAINT pk_iam_resource_state PRIMARY KEY (id)
);

COMMENT ON TABLE iam_resource_state IS 'IAM 资源状态定义表，登记业务资源可参与状态动作授权的状态。';
COMMENT ON COLUMN iam_resource_state.id IS '主键';
COMMENT ON COLUMN iam_resource_state.tenant_id IS '租户 ID，0 表示平台通用定义';
COMMENT ON COLUMN iam_resource_state.resource_key IS '业务资源标识，例如 sales-order';
COMMENT ON COLUMN iam_resource_state.state_code IS '状态编码，例如 DRAFT、SUBMITTED、APPROVED';
COMMENT ON COLUMN iam_resource_state.state_name IS '状态名称，例如 草稿、已提交、已审核';
COMMENT ON COLUMN iam_resource_state.description IS '状态说明';
COMMENT ON COLUMN iam_resource_state.sort_no IS '排序号';
COMMENT ON COLUMN iam_resource_state.is_enabled IS '是否启用';
COMMENT ON COLUMN iam_resource_state.metadata_json IS '扩展元数据，例如展示颜色、标签类型等';
COMMENT ON COLUMN iam_resource_state.created_by IS '创建人';
COMMENT ON COLUMN iam_resource_state.created_at IS '创建时间';
COMMENT ON COLUMN iam_resource_state.updated_by IS '更新人';
COMMENT ON COLUMN iam_resource_state.updated_at IS '更新时间';
COMMENT ON COLUMN iam_resource_state.deleted_by IS '删除人';
COMMENT ON COLUMN iam_resource_state.delete_reason IS '删除原因';
COMMENT ON COLUMN iam_resource_state.deleted_at IS '逻辑删除时间';

CREATE UNIQUE INDEX IF NOT EXISTS idx_iam_resource_state_active
    ON iam_resource_state (tenant_id, resource_key, state_code)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_iam_resource_state_resource
    ON iam_resource_state (resource_key, sort_no)
    WHERE deleted_at IS NULL;

