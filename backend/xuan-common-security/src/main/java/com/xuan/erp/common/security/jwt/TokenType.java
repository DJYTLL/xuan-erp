package com.xuan.erp.common.security.jwt;

/**
 * JWT Token 类型。
 *
 * <p>系统会同时使用访问令牌和刷新令牌，两类令牌的生命周期、使用场景和安全边界不同。
 * 访问令牌用于访问业务接口，应该短时有效；刷新令牌只用于换取新的访问令牌，不应该被业务接口直接接受。</p>
 *
 * <p>把令牌类型定义成枚举，可以让签发、解析和校验逻辑统一使用稳定的类型值，避免在代码中散落
 * {@code access}、{@code refresh} 之类的魔法字符串。</p>
 */
public enum TokenType {
    /**
     * 访问令牌。
     *
     * <p>客户端访问业务 API 时携带的令牌。资源服务或 Gateway 校验通过后，可以从中提取用户 ID、
     * 租户 ID、用户名和权限码等轻量身份字段。访问令牌不应承担刷新会话、长期记住登录态等职责。</p>
     */
    ACCESS,

    /**
     * 刷新令牌。
     *
     * <p>刷新令牌用于在访问令牌过期后换取新的访问令牌。它通常有更长的有效期，也更需要服务端存储、
     * 撤销和轮换控制。业务接口不应该把刷新令牌当作访问凭证使用。</p>
     */
    REFRESH
}
